DATASETS = list(T15)
HLAB = ["h1 (96/24)", "h2 (192/36)", "h3 (336/48)", "h4 (720/60)"]

def col(ds, h, mi, metric):
    return T15[ds][h][2*mi + (0 if metric == "mse" else 1)]

def report(metric):
    print(f"\n{'='*78}\nPER-HORIZON WILCOXON SIGNED-RANK, LVM (MAE+UVH) vs each baseline — {metric.upper()}")
    print(f"n = {len(DATASETS)} datasets per horizon; two-sided; negative diff = LVM better\n")
    hdr = f"{'baseline':<12}" + "".join(f"{h:>18}" for h in HLAB)
    print(hdr); print("-"*len(hdr))
    for mi, m in enumerate(METHODS):
        if m == "MAE":
            continue
        cells = []
        for h in range(4):
            a = [col(d, h, 0, metric) for d in DATASETS]
            b = [col(d, h, mi, metric) for d in DATASETS]
            diff = [x - y for x, y in zip(a, b)]
            try:
                stat, p = wilcoxon(a, b)
            except ValueError:
                p = float("nan")
            wins = sum(1 for x, y in zip(a, b) if x < y)
            md = statistics.median(diff)
            star = "*" if p < 0.05 else " "
            cells.append(f"{wins}/{len(DATASETS)} p={p:.3f}{star}")
        print(f"{m:<12}" + "".join(f"{c:>18}" for c in cells))

def mean_rank():
    print(f"\n{'='*78}\nMEAN RANK BY HORIZON (MSE; 1 = best of {len(METHODS)} methods)\n")
    hdr = f"{'method':<12}" + "".join(f"{h:>14}" for h in HLAB) + f"{'overall':>10}"
    print(hdr); print("-"*len(hdr))
    allr = {m: [] for m in METHODS}
    per = {m: [] for m in METHODS}
    for h in range(4):
        ranks = {m: [] for m in METHODS}
        for d in DATASETS:
            vals = [(col(d, h, i, "mse"), m) for i, m in enumerate(METHODS)]
            vals.sort()
            for r, (_, m) in enumerate(vals, 1):
                ranks[m].append(r)
        for m in METHODS:
            per[m].append(statistics.mean(ranks[m]))
            allr[m].extend(ranks[m])
    order = sorted(METHODS, key=lambda m: statistics.mean(allr[m]))
    for m in order:
        print(f"{m:<12}" + "".join(f"{v:>14.2f}" for v in per[m]) + f"{statistics.mean(allr[m]):>10.2f}")

if __name__ == "__main__":
    report("mse")
    report("mae")
    mean_rank()
